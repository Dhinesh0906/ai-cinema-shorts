"""Story writer (Qwen3.5 27B via Ollama by default). Produces StoryDraft then ShotPlanDraft."""
from __future__ import annotations

import json
import math
import random

from ..config import Config
from ..llm import chat_json
from ..schemas import KOKORO_VOICES, Finding, Screenplay, Shot, ShotPlanDraft, StoryDraft
from pydantic import BaseModel, Field

GENRES = ["horror", "psychological thriller", "science fiction", "mystery", "supernatural", "fantasy",
          "emotional drama", "suspense", "adventure"]
GENRE_ALIASES = {"sci-fi": "science fiction", "scifi": "science fiction", "thriller": "psychological thriller",
                 "drama": "emotional drama"}

WRITER_SYSTEM = """You are an award-winning short-film writer and cinematographer creating ORIGINAL vertical
(9:16) cinematic micro-films for YouTube Shorts. Rules:
- Completely original fiction. No real people, no celebrities, no franchise characters, no brand names.
- All characters are adults (18+). Characters are created specifically for this story.
- The film is generated by a local image-to-video model that renders 2.5-5 second shots. Each shot must
  be ONE simple, clearly visible physical action that a video model can render: walking, turning,
  reaching, opening, looking, lifting, falling, running. Avoid complex choreography, crowds, text on
  screen, hands doing fine manipulation, fights, or more than two people interacting.
- There is NO lip sync. Tell the story visually plus a narrator. Dialogue may only be voice-over or
  off-screen; never write on-screen speaking.
- Characters keep exactly the same face, hair and costume across all shots.
- Hook the viewer in the first two seconds. Escalate. End with a strong, surprising or haunting final image.
- Narration is sparse and evocative: at most about {wps} words per second of shot time."""


def normalize_genre(genre: str | None, rng: random.Random) -> str:
    if not genre or genre.lower() == "random":
        return rng.choice(GENRES)
    g = genre.lower().strip()
    return GENRE_ALIASES.get(g, g)


def shot_budget(cfg: Config, target: int) -> tuple[int, int, int]:
    lo = math.ceil(target / cfg.shot_max_seconds)
    hi = math.floor(target / cfg.shot_min_seconds)
    rec = min(max(lo, round(target / 4.5)), hi)
    return lo, rec, hi


def beat_plan(n: int) -> list[str]:
    """Exact beat per shot for an n-shot film: always hook first, climax second-last, ending last."""
    if n <= 3:
        return ["hook", "climax", "ending"][:n] if n == 3 else ["hook", "ending"][:n]
    middle = n - 3
    fill = ["beginning", "conflict", "escalation"]
    mids = [fill[min(len(fill) - 1, i * len(fill) // middle)] for i in range(middle)]
    return ["hook", *mids, "climax", "ending"]


def write_story(cfg: Config, genre: str, target: int, avoid: list[str], session: dict, seed: int,
                brief: str | None = None) -> StoryDraft:
    voices = ", ".join(sorted(KOKORO_VOICES))
    ask = (f"The owner's creative brief — follow it closely and choose the genre that fits it: \"{brief}\".\n"
           f"Write a new story for a {target}-second vertical cinematic short." if brief else
           f"Write a new {genre} story for a {target}-second vertical cinematic short.")
    user = f"""{ask}
Use 1-3 characters and 1-3 locations (fewer is better for visual continuity).
Give every character an exhaustive FIXED visual description (face, hair, body, costume colors and
materials, accessories) so an image model can redraw them identically.
Pick character voice_id and narrator_voice_id from: {voices}. The narrator voice should suit the genre.
Earlier finished films — do NOT reuse their premise, central object, twist or ending (a fresh idea is required):
{json.dumps(avoid[-40:])}
Return JSON only."""
    return chat_json(cfg, cfg.models.writer, WRITER_SYSTEM.format(wps=cfg.narration_wps), user, StoryDraft,
                     session=session, temperature=0.9, seed=seed)


def write_shots(cfg: Config, story: StoryDraft, target: int, session: dict, seed: int,
                feedback: list[Finding] | None = None) -> ShotPlanDraft:
    lo, rec, hi = shot_budget(cfg, target)
    fb = ""
    if feedback:
        fb = "\nA script reviewer found these problems; fix them:\n" + "\n".join(
            f"- [{f.severity}] {f.criterion}: {f.evidence} -> {f.recommended_correction}" for f in feedback)
    user = f"""Story (JSON): {story.model_dump_json()}

Write the shot list. Requirements:
- {lo}-{hi} shots (about {rec}); ids shot_01, shot_02, ... in order.
- Each duration between {cfg.shot_min_seconds} and {cfg.shot_max_seconds} seconds; durations sum to EXACTLY {target}.
- Beats in story order: hook first, then beginning, conflict, escalation, climax, ending. A film MUST have
  a hook, a climax and an ending. With {rec} shots use exactly these beats: {beat_plan(rec)}.
- character_ids / location_id must use the story ids. subject_count = number of visible people.
- narration: the narrator carries the story. Narrate most shots; total narration about
  {round(target * 1.4)}-{round(target * 2.0)} words for the whole film, and at most {cfg.narration_wps} words per second
  of any single shot's duration.
- image_prompt: the first frame (who, where, pose, framing, lighting). motion_prompt: the ONE visible
  action plus camera and environment motion during the shot.
- expected_action_sequence: 1-3 short ordered visible events. must_show: 2-5 concrete visual facts
  (costume colors, props, setting) a validator can confirm in a single frame.
- sfx: 0-2 short concrete sound effects.{fb}
Return JSON only."""
    return chat_json(cfg, cfg.models.writer, WRITER_SYSTEM.format(wps=cfg.narration_wps), user, ShotPlanDraft,
                     session=session, temperature=0.7, seed=seed, num_predict=28000)


class ShotPatch(BaseModel):
    shots: list[Shot] = Field(min_length=1)


class StoryPatch(BaseModel):
    story: StoryDraft


def revise(cfg: Config, sp: Screenplay, findings: list[Finding], session: dict, seed: int) -> Screenplay:
    """Rewrite only the affected parts: individual shots when findings name shots, else story + shots."""
    shot_ids = {s.id for s in sp.shots}
    affected = {a for f in findings for a in f.affected}
    notes = "\n".join(f"- [{f.severity}] {f.criterion} ({', '.join(f.affected)}): {f.evidence} -> "
                      f"{f.recommended_correction}" for f in findings)
    system = WRITER_SYSTEM.format(wps=cfg.narration_wps)
    if affected and affected <= shot_ids:
        targets = [s for s in sp.shots if s.id in affected]
        user = f"""Full screenplay for context (JSON): {sp.model_dump_json()}

Rewrite ONLY these shots: {sorted(affected)}. Keep their ids and keep each duration unchanged.
Required beat per shot id: {dict(zip([x.id for x in sp.shots], beat_plan(len(sp.shots))))}

(durations must still sum to {sp.target_seconds}). Fix:
{notes}
Return JSON {{"shots": [...]}} containing only the rewritten shots."""
        patch = chat_json(cfg, cfg.models.writer, system, user, ShotPatch, session=session, seed=seed)
        fixed = {s.id: s for s in patch.shots if s.id in affected}
        old = {s.id: s for s in targets}
        for sid, s in fixed.items():  # keep timing stable even if the model drifted
            s.duration = old[sid].duration
        return sp.model_copy(update={"shots": [fixed.get(s.id, s) for s in sp.shots]})
    user = f"""Screenplay (JSON): {sp.model_dump_json()}

Revise the story to fix these problems while keeping what works:
{notes}
Return JSON {{"story": ...}} with the full corrected story object."""
    story = chat_json(cfg, cfg.models.writer, system, user, StoryPatch, session=session, seed=seed).story
    plan = write_shots(cfg, story, sp.target_seconds, session, seed + 1, feedback=findings)
    return Screenplay(story_id=sp.story_id, target_seconds=sp.target_seconds, story=story, shots=plan.shots)
